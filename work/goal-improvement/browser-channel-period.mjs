import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir, writeFile, rm } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";
import { join } from "node:path";
import { seedPeriodFixture, removePeriodFixture, periodChannel } from "./channel-period-fixture.mjs";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE ?? join(homedir(), ".cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright"));
const mode = process.argv[2] ?? "after";
const directory = new URL("./evidence/round4/", import.meta.url);
const flag = new URL("../../.temp/goal-api-failure", import.meta.url);
await mkdir(directory,{recursive:true});
const fixture = await seedPeriodFixture();
const base = `http://127.0.0.1:3300/channels/${periodChannel.login}`;
const browser = await chromium.launch({headless:true});
const report = { fixture, runs:[] };
const dayAt = offset => new Date(Date.parse(fixture.endDay)+offset*86400000).toISOString().slice(0,10);
try {
  for (const width of [1440,768,390,320]) {
    const context = await browser.newContext({viewport:{width,height:900},hasTouch:width<=390,reducedMotion:"reduce"});
    await context.grantPermissions(["clipboard-read","clipboard-write"],{origin:"http://127.0.0.1:3300"});
    await context.route(/^https?:\/\/(?!127\.0\.0\.1(?=[:/]))/,route=>route.fulfill({status:200,contentType:"image/svg+xml",body:'<svg xmlns="http://www.w3.org/2000/svg"/>'}));
    const page=await context.newPage();
    const errors=[];
    page.on("pageerror",e=>errors.push(e.message));
    page.on("console",m=>{if(m.type()==="error")errors.push(m.text());});
    page.on("response",r=>{if(r.url().startsWith("http://127.0.0.1:3300") && r.status()>=500)errors.push(`HTTP ${r.status()}: ${new URL(r.url()).pathname}`);});
    await page.goto(`${base}?days=7&end=${fixture.endDay}`);
    await page.getByRole("heading",{name:"7-day history"}).waitFor();
    await page.getByRole("button",{name:"Messages",exact:true}).click();
    await page.getByRole("slider").focus();
    await page.getByRole("slider").press("Home");
    await page.waitForURL(url=>url.searchParams.get("day")===dayAt(-6));
    const selected=await page.locator(".channel-chart-values").innerText();
    assert.equal(new URL(page.url()).searchParams.get("measure"),"messages");
    await page.reload();
    await page.getByRole("heading",{name:"Chat over time"}).waitFor();
    assert.equal(await page.locator(".channel-chart-values").innerText(),selected);
    await page.getByRole("button",{name:"Copy view link"}).click();
    await page.getByRole("status").filter({hasText:"View link copied"}).waitFor();
    const copied=await page.evaluate(()=>navigator.clipboard.readText());
    assert.equal(new URL(copied).searchParams.get("end"),fixture.endDay);
    const shared=await context.newPage();
    await shared.goto(copied);
    await shared.getByRole("heading",{name:"Chat over time"}).waitFor();
    assert.equal(await shared.locator(".channel-chart-values").innerText(),selected);
    await shared.close();
    await page.getByRole("link",{name:`Streams on ${dayAt(-6)}`}).click();
    await page.getByText(`Active on ${dayAt(-6)} · UTC · Includes streams that began earlier`).waitFor();
    assert.ok(await page.locator(".channel-session-card").count()>0);
    await page.locator(".channel-session-card .recent-stream-title").first().click();
    await page.waitForURL(/\/streams\/goal-period-/);
    await page.goBack();
    await page.getByRole("navigation",{name:"Channel pages"}).getByRole("link",{name:"Overview",exact:true}).click();
    await page.getByRole("heading",{name:"Chat over time"}).waitFor();
    assert.equal(await page.locator(".channel-chart-values").innerText(),selected);
    await page.getByRole("link",{name:"90 days",exact:true}).click();
    await page.getByRole("heading",{name:"90-day history"}).waitFor();
    await page.getByRole("heading",{name:"Chat over time"}).waitFor();
    await page.locator(".channel-daily summary").click();
    assert.equal(await page.locator(".channel-daily tbody tr").count(),90);
    const zero=page.getByRole("rowheader",{name:fixture.zeroDay,exact:true}).locator("..");
    assert.deepEqual((await zero.locator("td").allTextContents()).slice(0,2),["0","0"]);
    const missing=page.getByRole("rowheader",{name:fixture.missingDay,exact:true}).locator("..");
    assert.deepEqual((await missing.locator("td").allTextContents()).slice(0,2),["—","—"]);
    if([1440,390].includes(width)) {
      await page.locator(".channel-daily summary").scrollIntoViewIfNeeded();
      await page.screenshot({path:fileURLToPath(new URL(`${mode}-daily-${width}.png`,directory))});
    }
    await page.locator(".channel-daily summary").click();
    await page.getByRole("button",{name:/Peak audience:/}).click();
    await page.getByRole("heading",{name:"Audience over time"}).waitFor();
    assert.equal(await page.getByRole("slider").evaluate(e=>e.getBoundingClientRect().height),44);
    await page.getByRole("slider").focus();
    await page.getByRole("slider").press("ArrowLeft");
    assert.notEqual(await page.getByRole("slider").evaluate(e=>getComputedStyle(e).outlineStyle),"none");
    assert.equal(await page.locator(".channel-chat-body").evaluate(e=>e.scrollWidth>e.clientWidth),false);
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.screenshot({path:fileURLToPath(new URL(`${mode}-channel-${width}.png`,directory)),fullPage:true});
    await page.locator(".channel-period-date summary").click();
    await page.getByLabel("Period ending (UTC)").fill(dayAt(-45));
    await page.getByRole("button",{name:"Apply date"}).click();
    await page.waitForURL(url=>url.searchParams.get("end")===dayAt(-45));
    await page.getByRole("heading",{name:"90-day history"}).waitFor();
    await page.getByRole("link",{name:"Latest",exact:true}).click();
    await page.getByRole("heading",{name:"Last 90 days"}).waitFor();
    await page.getByRole("link",{name:"Previous 90 days"}).click();
    await page.getByRole("heading",{name:"90-day history"}).waitFor();
    await page.getByRole("link",{name:"Next 90 days"}).click();
    await page.getByRole("heading",{name:"Last 90 days"}).waitFor();
    await page.goto(`${base}?days=7&days=90&end=2026-02-30&day=invalid&measure=invalid`);
    await page.getByRole("status").filter({hasText:"Some view options were invalid"}).waitFor();
    assert.equal(await page.getByRole("navigation",{name:"Period length"}).locator('[aria-current="page"]').innerText(),"30 days");
    await page.goto(`${base}?days=7&end=2011-01-07`);
    await page.getByRole("heading",{name:"No viewer observations in this period"}).waitFor();
    await page.locator(".channel-daily summary").click();
    assert.equal(await page.locator(".channel-daily tbody tr").count(),7);
    await page.getByRole("rowheader",{name:"2011-01-07"}).getByRole("link").click();
    await page.getByRole("heading",{name:"No streams on 2011-01-07"}).waitFor();
    await page.getByRole("link",{name:"Browse all streams",exact:true}).click();
    await page.locator(".channel-session-card").first().waitFor();
    await page.getByLabel("Active on (UTC)").fill(dayAt(-2));
    await page.getByRole("button",{name:"Find streams"}).click();
    await page.getByText(`Active on ${dayAt(-2)} · UTC · Includes streams that began earlier`).waitFor();
    await page.getByLabel("Active on (UTC)").fill(dayAt(-45));
    await page.getByRole("button",{name:"Find streams"}).click();
    await page.getByText(`Active on ${dayAt(-45)} · UTC · Includes streams that began earlier`).waitFor();
    await page.getByRole("navigation",{name:"Channel pages"}).getByRole("link",{name:"Overview",exact:true}).click();
    await page.getByRole("heading",{name:"7-day history"}).waitFor();
    assert.equal(new URL(page.url()).searchParams.get("end"),dayAt(-45));
    assert.ok((await page.locator(".channel-chart-values").innerText()).startsWith(dayAt(-45)));
    await page.goto(`${base}?days=7&end=${fixture.endDay}`);
    await page.getByRole("heading",{name:"Audience over time"}).waitFor();
    if(width===390) {
      await page.evaluate(()=>{Object.defineProperty(navigator,"clipboard",{value:{writeText:async()=>{throw new Error("Synthetic permission denial");}},configurable:true});});
      await page.getByRole("button",{name:"Copy view link"}).click();
      assert.ok((await page.getByLabel("Copy this view link").inputValue()).includes(`end=${fixture.endDay}`));
      await page.locator(".channel-audience svg").tap({position:{x:120,y:90}});
      assert.ok(new URL(page.url()).searchParams.has("day"));
      await page.evaluate(()=>document.documentElement.style.zoom="2");
      await page.screenshot({path:fileURLToPath(new URL(`${mode}-zoom-${width}.png`,directory))});
    }
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    assert.deepEqual(errors,[]);
    report.runs.push({width,selected,shared:copied,errors,overflow:false,sliderHeight:44});
    await context.close();
  }
  await writeFile(flag,`/api/channels/${periodChannel.login}/overview`);
  const page=await browser.newPage({viewport:{width:390,height:844}});
  // Exercise an uncached read. A harmless local cookie selects the existing
  // no-store request path; no authenticated identity or external OAuth is used.
  await page.context().addCookies([{name:"goal_qa",value:"period-recovery",domain:"127.0.0.1",path:"/"}]);
  await page.goto(`${base}?days=7&end=${dayAt(-4)}`);
  await page.getByRole("heading",{name:"Details unavailable"}).waitFor();
  await rm(flag,{force:true});
  await page.getByRole("button",{name:"Try again"}).click();
  await page.getByRole("heading",{name:"Audience over time"}).waitFor();
  assert.equal(new URL(page.url()).searchParams.get("end"),dayAt(-4));
  report.recovery="Actual API 503 -> retry -> same historical period";
  await page.close();
} catch(error) {
  report.failure=error.message;
  throw error;
} finally {
  await writeFile(new URL(`${mode}-browser.json`,directory),JSON.stringify(report,null,2));
  await rm(flag,{force:true});
  await browser.close();
  await removePeriodFixture();
}
console.log(JSON.stringify(report));
